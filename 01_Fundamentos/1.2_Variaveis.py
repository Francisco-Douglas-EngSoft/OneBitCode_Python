#Variaveis em Python
#Variaveis são usadas para armazenar informações na memória do computador.

nome = "João" #String
saudacao = "Olá, " + nome + "!" #Concatenação de strings
idade = 25 #Inteiro
salario = 3500.50 #Float
casado = True #Booleano

print(saudacao, type(saudacao)) #Saída: Olá, João!
print("Idade:", idade, type(idade)) #Saída: Idade: 25
print("Salário:", salario, type(salario)) #Saída: Salário: 3500.5
print("Casado:", casado, type(casado)) #Saída: Casado: True